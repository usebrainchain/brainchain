// Writes src/abi.ts from a forge build of this repository: run `forge build` at
// the root first. Every function is kept, not only the ones the verifier calls,
// so a queued change decodes against the same interfaces the brain showed Jev.
import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = new URL("../../../", import.meta.url);
const commit = execFileSync("git", ["-C", fileURLToPath(root), "rev-parse", "--short", "HEAD"], { encoding: "utf8" }).trim();

let source = `// Generated by scripts/abi.mjs from usebrainchain/brainchain ${commit}. Do not edit.\n`;
for (const name of ["DecisionLog", "TaskBoard", "ModelRegistry", "DecisionExecutor"]) {
  const artifact = JSON.parse(await readFile(new URL(`out/${name}.sol/${name}.json`, root), "utf8"));
  const items = artifact.abi.filter((item) => item.type === "function" || item.type === "event");
  const constant = `${name[0].toLowerCase()}${name.slice(1)}Abi`;
  source += `\nexport const ${constant} = [\n${items.map((item) => `  ${JSON.stringify(item)},`).join("\n")}\n] as const;\n`;
}
await writeFile(new URL("../src/abi.ts", import.meta.url), source);
