// Writes src/deployments.ts from deployments/*.json at the repository root, so
// the published package carries the contract sets it was built against.
import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../../../deployments/", import.meta.url);

// The key a decision page uses for a set in its address, such as ?set=v3-1.
const keyOf = (release) => {
  const [major, minor] = release.split(".");
  return minor === "0" ? `v${major}` : `v${major}-${minor}`;
};

function set(release, fromBlock, contracts, file) {
  if (!release || !Number.isInteger(fromBlock)) throw new Error(`${file}: every set needs a release and a fromBlock`);
  // Boards before 3.0.0 named tasks by id alone, which the subject check does not model.
  if (Number(release.split(".")[0]) < 3) throw new Error(`${file}: release ${release} predates 3.0.0, which this verifier reads`);
  const { TaskBoard: board, DecisionLog: log, DecisionExecutor: executor } = contracts;
  if (!board || !log || !executor) throw new Error(`${file}: release ${release} needs TaskBoard, DecisionLog and DecisionExecutor`);
  return { key: keyOf(release), release, fromBlock, board, log, executor };
}

const networks = {};
for (const name of ["mainnet", "testnet"]) {
  const file = `deployments/${name}.json`;
  const d = JSON.parse(await readFile(new URL(`${name}.json`, root), "utf8"));
  networks[name] = {
    chainId: d.chainId,
    name: d.network,
    rpc: d.rpc,
    sets: [
      set(d.release, d.fromBlock, d.contracts, file),
      ...(d.retired ?? []).map((r) => set(r.release, r.fromBlock, r.contracts, file)),
    ],
  };
}

const source = `// Generated by scripts/deployments.mjs from deployments/*.json. Do not edit.
import type { Address } from "viem";

export interface ContractSet {
  /** As in a decision page's address: v3 for 3.0.0, v3-1 for 3.1.0. */
  key: string;
  release: string;
  fromBlock: number;
  board: Address;
  log: Address;
  executor: Address;
}

export interface Network {
  chainId: number;
  name: string;
  rpc: string;
  /** The active set first, then the retired ones, newest first. */
  sets: ContractSet[];
}

export const NETWORKS: Record<"mainnet" | "testnet", Network> = ${JSON.stringify(networks, null, 2)};
`;
await writeFile(new URL("../src/deployments.ts", import.meta.url), source);
